#!/usr/bin/env python3
"""Sign and verify blocklist.bin files with ECDSA P-256 + SHA-256.

The ESP32-C3 firmware (`src/main.cpp`) verifies the DER signature with the
P-256 public key embedded in `src/blocklist_pubkey.h` (mbedTLS, streaming
SHA-256 so the 700 KB file never sits in RAM).

Key management:
  - Generate once:  sign_blocklist.py gen --priv <priv.pem> --pub-h <pub.h>
  - NEVER commit <priv.pem>. Back it up offline and, for CI releases, store
    the PEM text in the BLOCKLIST_SIGN_KEY GitHub Actions secret.
  - The .sig file is public: commit docs/blocklist.bin.sig alongside the
    prebuilt blocklist so remote auto-update verifies from day one.

Usage:
  sign_blocklist.py gen --priv tools/blocklist_signing.key --pub-h src/blocklist_pubkey.h
  sign_blocklist.py sign data/blocklist.bin tools/blocklist_signing.key [--out data/blocklist.bin.sig]
  sign_blocklist.py verify data/blocklist.bin data/blocklist.bin.sig --pub-key-pem <pub.pem>
"""
import argparse
import os
import sys

try:
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.exceptions import InvalidSignature
except ImportError:
    print('error: the "cryptography" package is required (pip install cryptography)',
          file=sys.stderr)
    sys.exit(2)


def gen_keypair(priv_path: str, pub_h_path: str, key_id: str = 'bl-keys-1') -> None:
    key = ec.generate_private_key(ec.SECP256R1())
    with open(priv_path, 'wb') as f:
        f.write(key.private_bytes(serialization.Encoding.PEM,
                                  serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    try:
        os.chmod(priv_path, 0o600)
    except OSError:
        pass
    pub = key.public_key().public_numbers()
    raw = b'\x04' + pub.x.to_bytes(32, 'big') + pub.y.to_bytes(32, 'big')
    with open(pub_h_path, 'w') as f:
        f.write('// P-256 public key trusted for blocklist signatures.\n')
        f.write('// Generated by tools/sign_blocklist.py — do NOT edit by hand.\n')
        f.write('#pragma once\n#include <stdint.h>\n')
        f.write('static const char* BL_KEY_ID = "%s";\n' % key_id)
        f.write('static const uint8_t BL_PUBKEY[65] = {\n')
        for i in range(0, len(raw), 12):
            f.write('  ' + ', '.join('0x%02x' % b for b in raw[i:i + 12]) + ',\n')
        f.write('};\n')
    print('wrote %s (KEEP SECRET, never commit)' % priv_path)
    print('wrote %s (safe to commit)' % pub_h_path)


def sign_file(bin_path: str, priv_pem_path: str, out_sig: str = None) -> str:
    """Sign a blocklist .bin; returns the .sig path. Signature is DER ECDSA."""
    with open(priv_pem_path, 'rb') as f:
        priv = serialization.load_pem_private_key(f.read(), password=None)
    if not isinstance(priv, ec.EllipticCurvePrivateKey) or \
            not isinstance(priv.curve, ec.SECP256R1):
        raise ValueError('signing key must be an EC P-256 private key')
    with open(bin_path, 'rb') as f:
        data = f.read()
    sig_der = priv.sign(data, ec.ECDSA(hashes.SHA256()))
    if out_sig is None:
        out_sig = bin_path + '.sig'
    with open(out_sig, 'wb') as f:
        f.write(sig_der)
    print('signed %s -> %s (%d bytes DER)' % (bin_path, out_sig, len(sig_der)))
    return out_sig


def verify_file(bin_path: str, sig_path: str, pub_key) -> bool:
    with open(bin_path, 'rb') as f:
        data = f.read()
    with open(sig_path, 'rb') as f:
        sig_der = f.read()
    try:
        pub_key.verify(sig_der, data, ec.ECDSA(hashes.SHA256()))
        return True
    except InvalidSignature:
        return False


def load_pubkey_pem(pub_pem_path: str):
    with open(pub_pem_path, 'rb') as f:
        return serialization.load_pem_public_key(f.read())


def main() -> None:
    ap = argparse.ArgumentParser(description='Sign/verify blocklist.bin (ECDSA P-256)')
    sub = ap.add_subparsers(dest='cmd', required=True)

    g = sub.add_parser('gen', help='generate a P-256 keypair')
    g.add_argument('--priv', required=True, help='output private key PEM (gitignore this!)')
    g.add_argument('--pub-h', required=True, help='output C header with public key')
    g.add_argument('--key-id', default='bl-keys-1')

    s = sub.add_parser('sign', help='sign a blocklist .bin')
    s.add_argument('bin', help='blocklist.bin to sign')
    s.add_argument('privkey', help='private key PEM')
    s.add_argument('--out', default=None, help='signature output (default: <bin>.sig)')

    v = sub.add_parser('verify', help='verify a blocklist .bin against a .sig')
    v.add_argument('bin')
    v.add_argument('sig')
    v.add_argument('--pub-key-pem', required=True)

    args = ap.parse_args()
    if args.cmd == 'gen':
        gen_keypair(args.priv, args.pub_h, args.key_id)
    elif args.cmd == 'sign':
        sign_file(args.bin, args.privkey, args.out)
    elif args.cmd == 'verify':
        ok = verify_file(args.bin, args.sig, load_pubkey_pem(args.pub_key_pem))
        print('VALID' if ok else 'INVALID')
        sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
